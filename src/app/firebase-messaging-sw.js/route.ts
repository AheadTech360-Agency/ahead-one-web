/*
 * GET /firebase-messaging-sw.js: the web push service worker.
 *
 * Served from a route handler so the public NEXT_PUBLIC_FIREBASE_* values can be injected
 * (only public values: these are already inlined into the browser bundle). The worker does not
 * load the Firebase SDK; it reads the FCM payload itself, shows the notification unless a
 * focused AheadOne window is open (that window already shows it in-app), and on click focuses
 * an existing window or opens a new one at the app-relative `link`.
 */

const config = {
  apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY ?? "",
  projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID ?? "",
  messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID ?? "",
  appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID ?? "",
};

const worker = `/* AheadOne push worker. Generated by src/app/firebase-messaging-sw.js/route.ts */
const FIREBASE_CONFIG = ${JSON.stringify(config)};

self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (event) => event.waitUntil(self.clients.claim()));

function targetFor(data, fallbackLink) {
  // The link wins; a message push without one opens its conversation.
  if (data && data.link) return data.link;
  if (data && data.conversation_id) return "/messages/" + encodeURIComponent(data.conversation_id);
  return fallbackLink;
}

function appUrl(raw) {
  try {
    const url = new URL(raw || "/inbox", self.location.origin);
    return url.origin === self.location.origin ? url.href : new URL("/inbox", self.location.origin).href;
  } catch (e) {
    return new URL("/inbox", self.location.origin).href;
  }
}

self.addEventListener("push", (event) => {
  let payload = {};
  try {
    payload = event.data ? event.data.json() : {};
  } catch (e) {
    return;
  }
  // Ignore pushes that didn't come from this project's sender.
  if (FIREBASE_CONFIG.messagingSenderId && payload.from && String(payload.from) !== FIREBASE_CONFIG.messagingSenderId) return;
  const n = payload.notification || {};
  const data = payload.data || {};
  const link = appUrl(targetFor(data, (payload.fcmOptions && payload.fcmOptions.link) || n.click_action));
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((windows) => {
      // The open app shows its own toast for normal notifications; test pushes carry always_show.
      if (data.always_show !== "1" && windows.some((w) => w.focused && w.visibilityState === "visible")) return;
      return self.registration.showNotification(n.title || "AheadOne", {
        body: n.body || "",
        // One notification per conversation (or link), so a burst of messages replaces the last one.
        tag: data.conversation_id ? "conv:" + data.conversation_id : link,
        renotify: true,
        data: { link },
      });
    }),
  );
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const link = appUrl(event.notification.data && event.notification.data.link);
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((windows) => {
      const same = windows.find((w) => new URL(w.url).origin === self.location.origin);
      if (same) {
        return same.focus().then((w) => (w && "navigate" in w ? w.navigate(link) : undefined)).catch(() => self.clients.openWindow(link));
      }
      return self.clients.openWindow(link);
    }),
  );
});
`;

export function GET() {
  return new Response(worker, {
    headers: {
      "Content-Type": "text/javascript; charset=utf-8",
      // Browsers re-check service workers anyway; never let a CDN pin an old one.
      "Cache-Control": "no-cache, no-store, must-revalidate",
    },
  });
}
